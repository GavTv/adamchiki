export interface ServiceItem {
  id: string;
  name: string;
  price: string;
  description: string;
  /** Individual DIKIDI booking link. Fill when the salon provides the links. */
  bookingUrl?: string;
}

export interface ServiceGroup {
  id: string;
  title: string;
  items: ServiceItem[];
}

export interface ServicePage {
  id: string;
  title: string;
  route: string;
  groups: Record<string, ServiceGroup>;
}

type ServiceEntry = Omit<ServiceItem, "id">;

const makeItems = (prefix: string, entries: ServiceEntry[]): ServiceItem[] =>
  entries.map((entry, index) => ({ ...entry, id: `${prefix}-${index + 1}` }));

